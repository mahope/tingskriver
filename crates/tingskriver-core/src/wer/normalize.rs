/// Lowercase Unicode letters, retain letters/digits and turn other characters
/// into word boundaries. No number expansion, aa/å folding or Unicode NFC.
pub fn normalize(text: &str) -> String {
    text.to_lowercase()
        .chars()
        .map(|c| if c.is_alphanumeric() { c } else { ' ' })
        .collect::<String>()
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
}
